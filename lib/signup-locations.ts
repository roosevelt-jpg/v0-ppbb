function areaList(names: string[]): string[] {
  const unique = [
    ...new Set(names.map((name) => name.trim()).filter((name) => name && name !== 'Other')),
  ]
  unique.sort((a, b) => a.localeCompare(b, 'en'))
  return [...unique, 'Other']
}

