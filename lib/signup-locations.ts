const AREA_ALIASES: Record<string, string> = {
  jlt: 'JLT',
  jvc: 'Jumeirah Village Circle',
  jvt: 'Jumeirah Village Triangle',
  jbr: 'Jumeirah Beach Residence',
  dip: 'Dubai Investment Park',
  dso: 'Dubai Silicon Oasis',
  tecom: 'Barsha Heights',
  'barsha heights (tecom)': 'Barsha Heights',
  'rak city': 'RAK City',
  'uaq city': 'UAQ City',
}

export function citiesForEmirate(emirate: string): string[] {
  return UAE_CITIES_BY_EMIRATE[emirate as UaeEmirate] || ['Other']
}

export function defaultCityForEmirate(emirate: string): string {
  const cities = citiesForEmirate(emirate)
  const preferred = [emirate, `${emirate} City`, 'RAK City', 'UAQ City', 'Abu Dhabi City']
  return preferred.find((name) => cities.includes(name)) || cities[0] || 'Other'
}

export function matchCityForEmirate(emirate: string, cityHint: string): string {
  const cities = citiesForEmirate(emirate)
  const hay = cityHint.trim().toLowerCase()
  if (!hay) return defaultCityForEmirate(emirate)
  const alias = AREA_ALIASES[hay]
  if (alias && cities.includes(alias)) return alias
  const exact = cities.find((city) => city.toLowerCase() === hay)
  if (exact) return exact
  const contained = cities
    .filter((city) => city !== 'Other' && hay.includes(city.toLowerCase()))
    .sort((a, b) => b.length - a.length)[0]
  if (contained) return contained
  return cities.includes('Other') ? 'Other' : defaultCityForEmirate(emirate)
}

export function isUaeCountry(country: string): boolean {
  const normalized = country.trim().toLowerCase()
  return normalized === 'united arab emirates' || normalized === 'uae'
}
